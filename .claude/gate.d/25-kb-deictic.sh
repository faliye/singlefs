#!/usr/bin/env bash
# gate-stage: kb 里的「本轮」锚不锚得到具体一轮
#
# `.claude/singlefs-ai-sop/rules/kb-discipline.md` 第 1 条要求每条事实**被单条取出时仍然成立**，
# 并点名禁了「如上所述 / 同上 / 见上文」。上游的 `doc-lint.sh` 拦的正是那一批。
#
# **它拦不到时间指代**：「本轮实测判绿」「这一轮踩的坑」——检索把这一条单独端出来时，
# 「本轮」是哪一轮无从得知，而模型不会说「我看不懂」，它会补一个。
# 2026-08-30 现查：kb 正文里这类指代 78 处，其中 22 处连一个日期都够不着。
#
# 判据：正文里出现 `本轮 / 这一轮 / 上一轮 / 前一轮 / 上轮` 时，
# **该行或它所属的最近一个标题里必须有日期**（`2026-08-30` 或 `08-30`）。
#
# 三类不判，各有理由：
#   · `下一轮` —— 指的是还没发生的任何一轮，本来就是泛指，锚不到也锚不该
#   · `本次 / 上次 / 这次` —— 它们多数挂在技术对象上（本次 diff、上次 scrub 的水位、
#     本次 fsync 的根），那是自足的；一律禁会把这条检查变成噪音，然后被关掉
#   · `## 历史版本` 节内 —— 每条历史都挂在 `### YYYY-MM-DD` 下，日期就是锚
set -uo pipefail
cd "${1:-$(dirname "$0")/../..}" || exit 2
KB=.claude/kb
bad() { printf '  ✗ %s\n' "$*"; }
ok()  { printf '  ✓ %s\n' "$*"; }
howto() { printf '     → %s\n' "$*"; }

[[ -d "$KB" ]] && mapfile -t hits < <(
  find "$KB" -name '*.md' | sort | while IFS= read -r f; do
    awk -v F="$f" '
      /^```/            { fence = !fence; next }
      fence             { next }
      /^#/              { head = $0
                          if ($0 ~ /^## *历史版本/) hist = 1
                          else if ($0 ~ /^## /)     hist = 0 }
      hist              { next }
      /本轮|这一轮|上一轮|前一轮|上轮/ {
        if ($0 ~ /20[0-9][0-9]-[0-9][0-9]-[0-9][0-9]/ || $0 ~ /[0-9][0-9]-[0-9][0-9]/) next
        if (head ~ /20[0-9][0-9]-[0-9][0-9]-[0-9][0-9]/ || head ~ /[0-9][0-9]-[0-9][0-9]/) next
        print F ":" NR "\t" substr($0, 1, 90)
      }' "$f"
  done
)

if ((${#hits[@]})); then
  bad "kb 正文里有 ${#hits[@]} 处「本轮」够不到任何日期"
  printf '     %s\n' "${hits[@]}"
  howto "把指代换成锚：写「2026-08-30 那一轮」「E41 那一轮」，或直接点名那次实验 / 那个日期。"
  howto "确实是泛指任何一轮的规则句，改写成不带指代的说法（例：「跑它的那一轮」→「产出这份输出的那次运行」）。"
  howto "判据是检索：这一条被单独端出来时，读的人能不能知道是哪一轮。"
  exit 1
fi
ok "kb 正文里的时间指代都锚得到具体一轮"
