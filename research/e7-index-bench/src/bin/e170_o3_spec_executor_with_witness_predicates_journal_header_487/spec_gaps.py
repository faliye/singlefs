@dataclass
class GapsHitInOneState:
    """一态走过的路上撞上的欠一句表编号（暂代跑法照走，严格跑法据此判「规约欠一句」）。"""

    identifiers: set[str] = field(default_factory=set)

    def record_hit(self, gap_identifier: str) -> None:
        assert gap_identifier in ALL_GAP_IDENTIFIERS, f"{gap_identifier} 不在欠一句表里"
        self.identifiers.add(gap_identifier)

    def sorted_identifiers(self) -> list[str]:
        return sorted(self.identifiers)
