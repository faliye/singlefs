# G1 第四批：第一批变形里放过的几种，各取同类的别的写法。
from cases_heavy import add
N = 0
def fz(cmd, why="同一载荷的另一种写法", agent="implementation-writer", **kw):
    global N
    N += 1
    add("Y%03d" % N, "变形二", cmd, 2, why, agent=agent, truth=True, **kw)
# trap
for sig in ("EXIT", "0", "ERR", "DEBUG", "RETURN", "SIGTERM"):
    fz("trap 'cargo test --all' %s; %s" % (sig, "false" if sig == "ERR" else "true"))
fz("trap -- 'cargo test --all' EXIT")
fz("f() { trap 'cargo test --all' RETURN; }; f")
fz("(trap 'cargo test --all' EXIT)")
fz("trap 'bash heavy.sh' EXIT")
fz("trap 'echo' EXIT; trap 'cargo test --all' EXIT")
# alias
fz("alias cargo='cargo test --all'\nshopt -s expand_aliases\ncargo")
fz("shopt -s expand_aliases\nalias ll='bash heavy.sh'\nll")
fz("bash -O expand_aliases -c \"alias c='cargo test --all'\nc\"")
# /dev/stdin 与 fd
fz(". /dev/stdin <<< 'cargo test --all'")
fz("bash /dev/fd/0 <<< 'cargo test --all'")
fz("bash /proc/self/fd/0 <<< 'cargo test --all'")
fz("bash /dev/stdin < heavy.sh")
fz("sh /dev/stdin < heavy.sh")
fz("exec 3< heavy.sh; bash <&3")
fz("exec 3< heavy.sh; bash 0<&3")
fz("bash 0< heavy.sh")
fz("exec < heavy.sh; sh")
fz("exec < heavy.sh; bash -s")
fz("exec 0< heavy.sh; bash")
fz("{ bash; } < heavy.sh")
fz("( bash ) < heavy.sh")
fz("while true; do bash; break; done < heavy.sh")
fz("if true; then bash; fi < heavy.sh")
# 波浪号与目录
fz("bash ~+/heavy.sh")
fz("bash ~-/heavy.sh", "~- 是 $OLDPWD，未设时原样")
fz("cd . ; bash ~+/heavy.sh")
fz("cd missing_d137 2>/dev/null; bash heavy.sh")
fz("cd missing_d137 || true; bash heavy.sh")
fz("cd missing_d137; bash heavy.sh")
fz("cd missing_d137 || :; cargo test --all")
fz("(cd missing_d137 || true) ; bash heavy.sh")
fz("cd missing_d137/ && :; bash heavy.sh")
fz("pushd missing_d137 >/dev/null 2>&1; bash heavy.sh")
fz("cd \"$(echo missing_d137)\" 2>/dev/null; bash heavy.sh")
fz("env -C missing_d137 bash heavy.sh 2>/dev/null; bash heavy.sh")
fz("OLDPWD=. ; cd - >/dev/null; bash heavy.sh")
fz("cd -P . ; bash heavy.sh")
fz("cd ./ ; bash heavy.sh")
fz("cd .. ; bash sandbox/heavy.sh")
fz("cd ..; cd sandbox; bash heavy.sh")
fz("CDPATH=. cd sandbox 2>/dev/null; bash heavy.sh")
fz("cd -- . ; bash heavy.sh")
fz("cd \"\"; bash heavy.sh")
fz("cd ''; bash heavy.sh")
fz("cd ' '; bash heavy.sh")
# 改名的 shell
fz("cp /bin/bash ./mysh_d137; ./mysh_d137 heavy.sh")
fz("ln -sf /bin/bash ./mysh_d137b; ./mysh_d137b -c 'cargo test --all'")
fz("busybox sh heavy.sh", "busybox sh（已知没认同类：别的 shell）")
fz("rbash -c 'cargo test --all'")
fz("/bin/rbash heavy.sh")
fz("exec -a notashell /bin/bash heavy.sh")
fz("(exec -a x bash heavy.sh)")
fz("$BASH heavy.sh")
fz("\"$BASH\" -c 'cargo test --all'")
fz("${BASH} heavy.sh")
fz("$SHELL heavy.sh")
fz("$0 heavy.sh")
# 选项
fz("bash -euo pipefail -c 'cargo test --all'", "常见写法 -euo pipefail")
