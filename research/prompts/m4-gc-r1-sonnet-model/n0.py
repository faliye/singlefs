# N0 下界草算（推的）：GC 自己每次发布新写 c 个提交内生块、换下 c 个；换下的要等根环转一圈（3S 条根）才回收，
# 所以稳态里 defer 里滞留 (3S - 1) * c 个块，它们占着整段；加一段给下一次开段。
# S = 每区槽数（格式常量：下限 4、mkfs 默认 8、上限 16），c = 一次发布新写的提交内生块数（取 5 / 10 / 13，D16 已定项 1 里 c_max 的两个例值与新池 11 块之间）
import math
SEG = 64
print("S  c  滞留块数  N0下界")
for s in (4, 8, 16):
    for c in (5, 10, 13):
        held = (3 * s - 1) * c
        print(s, c, held, math.ceil(held / SEG) + 1)
